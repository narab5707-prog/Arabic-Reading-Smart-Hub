// Helper to get random subtopic for a category
export function getRandomSubtopic(categoryId: string): string {
  const cat = TOPIC_CATEGORIES.find((c) => c.id === categoryId);
  if (!cat || cat.subtopics.length === 0) return 'Kehidupan Sehari-hari';
  const randomIndex = Math.floor(Math.random() * cat.subtopics.length);
  return cat.subtopics[randomIndex];
}

// Helper to find category by subtopic
export function findCategoryBySubtopic(subtopic: string): TopicCategory | undefined {
  return TOPIC_CATEGORIES.find((cat) =>
    cat.subtopics.some((s) => s.toLowerCase().includes(subtopic.toLowerCase()))
  );
}
